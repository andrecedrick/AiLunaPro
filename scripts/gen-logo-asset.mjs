// One-off generator: decode the official AiLunaPro logo PNG, trim transparent
// padding, composite onto white, deflate, and emit a deterministic embedded
// asset module for the PDF writer. Run: node scripts/gen-logo-asset.mjs
// The PDF build then uses ONLY the committed constant (no network, deterministic).
import { writeFileSync } from 'node:fs';
import { inflateSync, deflateSync } from 'node:zlib';

const LOGO_URL = 'https://res.cloudinary.com/dhtnegf9d/image/upload/v1777320369/6_xldhxr.png';
const png = Buffer.from(await (await fetch(LOGO_URL)).arrayBuffer());
if (png.slice(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error('not a PNG');
const W = png.readUInt32BE(16), H = png.readUInt32BE(20), bd = png[24], ct = png[25];
if (bd !== 8 || ct !== 6) throw new Error(`expected 8-bit RGBA, got bd=${bd} ct=${ct}`);

// Concatenate IDAT chunks.
const idat = [];
for (let p = 8; p < png.length;) {
  const len = png.readUInt32BE(p);
  const type = png.toString('latin1', p + 4, p + 8);
  if (type === 'IDAT') idat.push(png.subarray(p + 8, p + 8 + len));
  p += 12 + len;
  if (type === 'IEND') break;
}
const raw = inflateSync(Buffer.concat(idat));

// Unfilter scanlines (RGBA, bpp=4).
const bpp = 4, stride = W * bpp;
const img = Buffer.alloc(H * stride);
const paeth = (a, b, c) => { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); return pa <= pb && pa <= pc ? a : pb <= pc ? b : c; };
for (let y = 0; y < H; y++) {
  const ft = raw[y * (stride + 1)];
  const inRow = raw.subarray(y * (stride + 1) + 1, y * (stride + 1) + 1 + stride);
  const out = img.subarray(y * stride, y * stride + stride);
  for (let i = 0; i < stride; i++) {
    const a = i >= bpp ? out[i - bpp] : 0;
    const b = y > 0 ? img[(y - 1) * stride + i] : 0;
    const c = (i >= bpp && y > 0) ? img[(y - 1) * stride + i - bpp] : 0;
    let v = inRow[i];
    if (ft === 1) v += a; else if (ft === 2) v += b; else if (ft === 3) v += (a + b) >> 1; else if (ft === 4) v += paeth(a, b, c);
    out[i] = v & 0xff;
  }
}

// Bounding box of non-transparent pixels (alpha > 16).
let minX = W, minY = H, maxX = -1, maxY = -1;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  if (img[(y * W + x) * 4 + 3] > 16) { if (x < minX) minX = x; if (x > maxX) maxX = x; if (y < minY) minY = y; if (y > maxY) maxY = y; }
}
const cw = maxX - minX + 1, chh = maxY - minY + 1;

// Crop + composite over white -> opaque RGB.
const rgb = Buffer.alloc(cw * chh * 3);
for (let y = 0; y < chh; y++) for (let x = 0; x < cw; x++) {
  const s = ((minY + y) * W + (minX + x)) * 4;
  const a = img[s + 3] / 255;
  const o = (y * cw + x) * 3;
  for (let k = 0; k < 3; k++) rgb[o + k] = Math.round(img[s + k] * a + 255 * (1 - a));
}

const def = deflateSync(rgb, { level: 9 });
const b64 = def.toString('base64');
const out = `// AUTO-GENERATED by scripts/gen-logo-asset.mjs — official AiLunaPro logo,
// trimmed + composited onto white, deflated RGB (DeviceRGB, 8bpc). Deterministic.
export const LOGO_ASSET = {
  width: ${cw},
  height: ${chh},
  /** zlib-deflated raw RGB (base64). */
  deflatedRgbB64:
${JSON.stringify(b64).replace(/(.{120})/g, '$1"+\n    "')},
};
`;
writeFileSync('worker/src/lib/pdf/logo-asset.ts', out);
console.log(`emitted logo-asset.ts  crop=${cw}x${chh}  deflated=${def.length}B  b64=${b64.length}chars`);
